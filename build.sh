#!/bin/bash
THIS_DIR=$(cd `dirname $0`; pwd)
MUSA_HOME=${MUSA_HOME:-/usr/local/musa}

export NVSHMEM_SHMEM_SUPPORT=0 && \
NVSHMEM_UCX_SUPPORT=0 \
NVSHMEM_USE_NCCL=0 \
NVSHMEM_IBGDA_SUPPORT=1 \
NVSHMEM_IBGDA_SUPPORT_GPUMEM_ONLY=0 \
NVSHMEM_PMIX_SUPPORT=0 \
NVSHMEM_GPU_COLL_USE_LDST=1 \
NVSHMEM_TIMEOUT_DEVICE_POLLING=0 \
NVSHMEM_USE_GDRCOPY=1 \
GDRCOPY_HOME=/usr \
NVSHMEM_ENABLE_ALL_DEVICE_INLINING=1 \
NVSHMEM_PREFIX=/usr/local/mtshmem \
NVSHMEM_DEBUG=0 \
NVSHMEM_TRACE=0 \
NVSHMEM_WARP_SIZE_128=0 \
NVSHMEM_BUILD_PACKAGES=1 \
NVSHMEM_BUILD_TESTS=0 \
NVSHMEM_BUILD_EXAMPLES=0 \
NVSHMEM_COVERAGE_TEST=${NVSHMEM_COVERAGE_TEST:-0} \
cmake -S ${THIS_DIR} -B ${THIS_DIR}/build/ \
  -DCMAKE_BUILD_TYPE=Release \
  -DCMAKE_MUSA_ARCHITECTURES=mp_31 \
  -DCMAKE_MODULE_PATH=${MUSA_HOME}/cmake \
  -DCMAKE_VERBOSE_MAKEFILE=OFF \
  -DNVSHMEM_BUILD_BITCODE_LIBRARY=1
